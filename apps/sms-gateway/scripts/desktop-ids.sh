#!/usr/bin/env bash
# Desktop install / data path helpers for this app (shipped inside its
# packages). Each Wadhu app owns its copy after scripts/new-app.sh.
# Requires WADHU_APP_ID and WADHU_APP_LABEL (from env/*.env or
# install-manifest.env). Overrides: WADHU_INSTALL_SLUG, WADHU_BIN_NAME,
# WADHU_PROGRAMS_NAME.
#
# Template prod:  com.wadhu.smsgateway       · "SMS Gateway"
# Template dev:   com.wadhu.smsgateway.debug · "SMS Gateway Dev"

desktop_is_debug() {
  [[ "${WADHU_APP_ID:-}" == *.debug ]] || [[ "${WADHU_ENV:-}" == "development" ]]
}

# Short folder slug under ~/.local/lib and for package layout (no spaces).
desktop_install_slug() {
  local base="${WADHU_INSTALL_SLUG:-wadhu-sms-gateway}"
  if desktop_is_debug; then
    echo "$base-debug"
  else
    echo "$base"
  fi
}

# Windows Programs folder name (spaces OK). The env label already
# carries the Dev suffix on development builds.
desktop_programs_name() {
  echo "${WADHU_PROGRAMS_NAME:-${WADHU_APP_LABEL:-SMS Gateway}}"
}

# CLI / shortcut binary base name.
desktop_bin_name() {
  local base="${WADHU_BIN_NAME:-wadhu-sms-gateway}"
  if desktop_is_debug; then
    echo "$base-dev"
  else
    echo "$base"
  fi
}

# Freedesktop desktop file id (no .desktop suffix).
desktop_entry_id() {
  echo "${WADHU_APP_ID:-com.wadhu.smsgateway}"
}

# App data directory (same key the app uses via dirs::data_dir + APP_ID).
desktop_data_dir_linux() {
  echo "${XDG_DATA_HOME:-$HOME/.local/share}/${WADHU_APP_ID:?}"
}

desktop_data_dir_windows_hint() {
  echo "%APPDATA%\\${WADHU_APP_ID:?}"
}

# Installed app files: binary + resources + uninstall + manifest.
desktop_install_dir_linux() {
  if [[ -n "${DESKTOP_INSTALL_DIR_LINUX:-}" ]]; then
    echo "$DESKTOP_INSTALL_DIR_LINUX"
    return
  fi
  echo "$HOME/.local/lib/$(desktop_install_slug)"
}

desktop_bin_dir_linux() {
  echo "${XDG_BIN_HOME:-$HOME/.local/bin}"
}

desktop_applications_dir_linux() {
  echo "${XDG_DATA_HOME:-$HOME/.local/share}/applications"
}

# Write a small manifest the uninstaller reads (re-runnable after partial delete).
desktop_write_manifest() {
  local dest="${1:?}"
  mkdir -p "$(dirname "$dest")"
  cat >"$dest" <<EOF
# Generated by Wadhu desktop install — do not edit unless you know why.
WADHU_ENV=${WADHU_ENV:-production}
WADHU_APP_ID=${WADHU_APP_ID:?}
WADHU_APP_LABEL=${WADHU_APP_LABEL:?}
INSTALL_SLUG=$(desktop_install_slug)
BIN_NAME=$(desktop_bin_name)
ENTRY_ID=$(desktop_entry_id)
INSTALLED_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF
}

desktop_load_manifest() {
  local file="${1:?}"
  [[ -f "$file" ]] || return 1
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line#"${line%%[![:space:]]*}"}"
    [[ -z "$line" || "$line" == \#* ]] && continue
    [[ "$line" != *=* ]] && continue
    local key="${line%%=*}"
    local value="${line#*=}"
    export "$key=$value"
  done <"$file"
}

# Prompt whether to wipe the app's local data directory. Sets
# DESKTOP_WIPE_ARGS to "all" when the owner chooses wipe, else empty.
desktop_prompt_wipe_data() {
  local data_dir="${1:?}"
  local label="${WADHU_APP_LABEL:-SMS Gateway}"
  DESKTOP_WIPE_ARGS=""
  echo
  echo "$label — local data:"
  echo "  $data_dir"
  if [[ ! -e "$data_dir" ]]; then
    echo "  (no data directory found — nothing to remove)"
    return 1
  fi
  if [[ ! -t 0 ]]; then
    echo "(non-interactive: keeping all local data)"
    return 1
  fi
  local ans=""
  echo
  echo "Delete all local data for this app id? [y/N]"
  read -r -p "> " ans || true
  case "${ans,,}" in
    y|yes) DESKTOP_WIPE_ARGS="all"; return 0 ;;
    *) return 1 ;;
  esac
}

# Remove the data dir when DESKTOP_WIPE_ARGS is set. Prefer the app binary's
# --uninstall-wipe if present; otherwise rm -rf the directory.
desktop_apply_wipe_data() {
  local data_dir="${1:?}"
  local exe="${2:-}"
  if [[ -z "${DESKTOP_WIPE_ARGS:-}" ]]; then
    return 0
  fi
  if [[ -n "$exe" && -x "$exe" ]]; then
    echo "Wiping: $DESKTOP_WIPE_ARGS"
    "$exe" --uninstall-wipe $DESKTOP_WIPE_ARGS || true
    return 0
  fi
  echo "Removing local data directory: $data_dir"
  rm -rf "$data_dir"
}
